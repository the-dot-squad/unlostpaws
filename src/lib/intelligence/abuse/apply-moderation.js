import { ModerationReport } from "@/models/moderation-report";
import { setListingStatus } from "@/lib/listings/status";
import { getAppSettings } from "@/lib/services/settings";
import { softRemoveListing } from "@/lib/listings/purge-listing";

/**
 * Build human-readable summary for moderator queue.
 *
 * @param {number} abuseScore
 * @param {import("./assess-risk").AbuseSignal[]} signals
 */
function buildDetailsSummary(abuseScore, signals) {
  const pct = Math.round(abuseScore * 100);
  const top = signals
    .slice(0, 5)
    .map((s) => `${s.code} (${Math.round(s.weight * 100)}%)`)
    .join("; ");
  return `Automated abuse assessment: ${pct}% risk. Signals: ${top || "none"}.`;
}

/**
 * Apply tiered moderation actions from an abuse assessment.
 *
 * @param {Object} params
 * @param {import("mongoose").Document} params.listing
 * @param {number} params.abuseScore
 * @param {import("./assess-risk").AbuseSignal[]} params.signals
 * @param {import("./assess-risk").RelatedListingEvidence[]} params.relatedListings
 * @returns {Promise<{ action: "none"|"report"|"review"|"removed", reported: boolean }>}
 */
export async function applyModeration({ listing, abuseScore, signals, relatedListings }) {
  const settings = await getAppSettings();
  const reportThreshold = settings.abuseReportThreshold ?? 0.7;
  const reviewThreshold = settings.abuseReviewThreshold ?? 0.82;
  const removeThreshold = settings.abuseRemoveThreshold ?? 0.95;

  if (abuseScore < reportThreshold) {
    return { action: "none", reported: false };
  }

  const evidence = {
    riskScore: abuseScore,
    signals,
    relatedListings,
  };

  const details = buildDetailsSummary(abuseScore, signals);

  if (abuseScore >= removeThreshold && listing.status !== "removed") {
    await softRemoveListing(listing, {
      reason: "duplicate",
      note: details,
      silent: false,
    });

    await createAutoReport(listing, evidence, details, "auto_soft_remove");
    return { action: "removed", reported: true };
  }

  if (abuseScore >= reviewThreshold && listing.status === "active") {
    await setListingStatus(listing, "under_review");
    await createAutoReport(listing, evidence, details, "auto_under_review");
    return { action: "review", reported: true };
  }

  await createAutoReport(listing, evidence, details, "auto_flag");
  return { action: "report", reported: true };
}

/**
 * @param {import("mongoose").Document} listing
 * @param {object} evidence
 * @param {string} details
 * @param {string} auditAction
 */
async function createAutoReport(listing, evidence, details, auditAction) {
  const existing = await ModerationReport.findOne({
    listingId: listing._id,
    reporterId: "system",
    reason: "duplicate",
    status: { $in: ["open", "reviewing"] },
  });

  if (existing) {
    existing.evidence = evidence;
    existing.details = details;
    existing.auditLog.push({
      action: auditAction,
      by: "system",
      note: `Updated assessment — risk ${Math.round(evidence.riskScore * 100)}%`,
      at: new Date(),
    });
    await existing.save();
    return;
  }

  await ModerationReport.create({
    listingId: listing._id,
    reporterId: "system",
    reason: "duplicate",
    details,
    evidence,
    status: "open",
    autoGenerated: true,
    auditLog: [{ action: auditAction, by: "system", note: details }],
  });

  listing.reportCount = (listing.reportCount || 0) + 1;
  await listing.save();
}
