/**
 * Wipe intelligence pipeline data and re-enqueue active listings.
 * Usage: node --env-file=.env.local scripts/reset-intelligence-data.mjs
 */

import mongoose from "mongoose";
import { truncateMlCollections } from "../src/lib/qdrant/client.js";
import { enqueueListingProcessing } from "../src/lib/intelligence/queue.js";
import { env } from "../src/config/env.js";

const DATABASE_URL = env.db.url;

async function main() {
  await mongoose.connect(DATABASE_URL);
  const db = mongoose.connection.db;

  const [listingImages, listingMatches, autoReports] = await Promise.all([
    db.collection("listingimages").deleteMany({}),
    db.collection("listingmatches").deleteMany({}),
    db.collection("moderationreports").deleteMany({ autoGenerated: true }),
  ]);

  const listings = await db.collection("listings").updateMany(
    { status: { $in: ["active", "under_review"] } },
    {
      $set: {
        processingStatus: "pending",
        processingError: "",
        embeddingModel: "",
        lastMatchScanAt: null,
      },
    }
  );

  console.log("Deleted ListingImage:", listingImages.deletedCount);
  console.log("Deleted ListingMatch:", listingMatches.deletedCount);
  console.log("Deleted auto ModerationReport:", autoReports.deletedCount);
  console.log("Reset listings:", listings.modifiedCount);

  await truncateMlCollections();

  const active = await db
    .collection("listings")
    .find({ status: { $in: ["active", "under_review"] } })
    .project({ _id: 1, images: 1, type: 1, petType: 1 })
    .toArray();

  let enqueued = 0;
  for (const listing of active) {
    const urls = (listing.images || []).map((i) => i.url).filter(Boolean);
    if (!urls.length) continue;
    const result = await enqueueListingProcessing({
      listingId: listing._id.toString(),
      imageUrls: urls,
      listingType: listing.type,
      petType: listing.petType,
    });
    if (result.ok) enqueued += 1;
  }

  console.log("Re-enqueued listings:", enqueued);
  await mongoose.disconnect();
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
